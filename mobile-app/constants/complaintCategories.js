export function getComplaintCategory(id) {
  return COMPLAINT_CATEGORY_OPTIONS.find((category) => category.id === id) || null;
}

export function categoryMatchesQuery(category, query) {
  const needle = query.trim().toLowerCase();
  if (!needle) return true;
  const groupName = CATEGORY_GROUPS[category.group]?.name || '';
  return [category.name, category.description, category.section, groupName]
    .filter(Boolean)
    .some((value) => value.toLowerCase().includes(needle));
}
